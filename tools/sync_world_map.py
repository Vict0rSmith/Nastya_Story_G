"""Compile canonical draw.io topology and location access cards into runtime data.

Run with --check in validation; no runtime dependency on docs or XML parsing.
"""
import argparse
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "game/content/world_map.rpy"
VISUAL_TESTS = ROOT / "game/tests/navigation_visual_tests.rpy"


def read_nodes():
    root = ET.parse(ROOT / "docs/graphs/map.drawio").getroot()
    nodes = {}
    for element in root.iter():
        if not element.get("mapNodeId"):
            continue
        cell = element.find("mxCell") if element.tag == "UserObject" else element
        style = cell.get("style", "")
        nodes[element.get("id")] = dict(
            id=element.get("mapNodeId"), name=element.get("label", element.get("value")),
            parent=cell.get("parent"),
            kind="group" if "swimlane" in style else "router" if "rhombus" in style else "location",
        )
    assert len({n["id"] for n in nodes.values()}) == len(nodes), "Duplicate mapNodeId"
    return root, nodes


def compile_world():
    root, nodes = read_nodes()
    cards = {}
    for folder in ("locations", "hyperclusters"):
        for path in (ROOT / "docs/world" / folder).glob("*.md"):
            text = path.read_text(encoding="utf-8")
            if not text.startswith("---\n"):
                continue
            meta = dict(re.findall(r"^(\w+):\s*(.*)$", text.split("---", 2)[1], re.M))
            if "map_node_id" in meta:
                assert meta["map_node_id"] not in cards, "Duplicate map card"
                cards[meta["map_node_id"]] = meta
    world = {}
    for node in nodes.values():
        meta = cards[node["id"]]
        world[node["id"]] = dict(name=node["name"], kind=node["kind"],
            parent=nodes.get(node["parent"], {}).get("id"),
            access_state=meta.get("access_state", "tbd"),
            access_condition=meta.get("access_condition", "TBD").strip('"'), transitions={})
    links = []
    for cell in root.iter("mxCell"):
        if cell.get("edge") != "1":
            continue
        source, target = nodes[cell.get("source")]["id"], nodes[cell.get("target")]["id"]
        style = dict(part.split("=", 1) for part in cell.get("style", "").split(";") if "=" in part)
        start, end = style.get("startArrow", "none"), style.get("endArrow", "classic")
        if "router" in (world[source]["kind"], world[target]["kind"]):
            # Arrowless router links are system connections, not walking edges.
            if end != "none" or start == end == "none": links.append((source, target))
            if start != "none" or start == end == "none": links.append((target, source))
        else:
            assert world[source]["kind"] == world[target]["kind"] == "location"
            if end != "none": world[source]["transitions"][target] = None
            if start != "none": world[target]["transitions"][source] = None
    # Movement policy: TRANSPORT_SPEC, owner decision 2026-09-07.
    def building(node_id):
        if node_id in {"loc_building_yard", "loc_playground", "loc_masha_school_sports_ground"}:
            return None
        if node_id in {"loc_medical_institute_building_floor_1", "loc_medical_institute_admissions"}:
            return "medical_building"
        parent = world[node_id]["parent"]
        result = None
        while parent:
            if parent.startswith("loc_"): result = parent
            parent = world[parent]["parent"]
        return result
    for source, node in world.items():
        for target in node["transitions"]:
            node["transitions"][target] = 1 if building(source) and building(source) == building(target) else 5
    routes = {}
    for router, node in world.items():
        if node["kind"] != "router": continue
        for source, target in links:
            if target != router: continue
            for via, destination in links:
                if via == router and destination != source:
                    routes.setdefault(source, {})[destination] = dict(router=router, mode="bus", duration_minutes=20)
    return world, routes


def render():
    world, routes = compile_world()
    def literal(value):
        return repr(value)
    return ("# Generated by tools/sync_world_map.py; edit canonical sources, then regenerate.\n"
        "init -60 python:\n    WORLD_MAP = {\n" +
        "".join("        %r: %s,\n" % (key, literal(value)) for key, value in world.items()) +
        "    }\n    TRANSPORT_ROUTES = " + literal(routes) + "\n"
        "    for _map_id, _map_node in WORLD_MAP.items():\n"
        "        if _map_node['kind'] == 'location' or _map_id == 'loc_masha_school':\n"
        "            register_location(_map_id, **_map_node)\n")


def render_visual_tests():
    world, _ = compile_world()
    locations = [key for key, node in world.items() if node["kind"] == "location"]
    return '''# Generated by tools/sync_world_map.py.
testsuite navigation_visual:
    testcase every_location_hud:
        parameter map_location = %r
        $ renpy.store.game_state = create_new_game_state()
        $ game_state.location_id = map_location
        $ _prepare_visual_gameplay_context()
        run Show("game_hud")
        pause 0.15
        assert screen "game_hud"
        $ navigation_size = renpy.render(renpy.get_widget("game_hud", "world_navigation"), 912, 198, 0, 0).get_size()
        $ actions_size = renpy.render(renpy.get_widget("game_hud", "world_actions"), 912, 198, 0, 0).get_size()
        assert eval (navigation_size[0] <= 912 and navigation_size[1] <= 198)
        assert eval (actions_size[0] <= 912 and actions_size[1] <= 198)
        screenshot (map_location + ".png")
        run Hide("game_hud")
''' % locations


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in ((OUTPUT, render()), (VISUAL_TESTS, render_visual_tests())):
        if args.check:
            assert path.read_text(encoding="utf-8") == expected, "Run tools/sync_world_map.py"
        else:
            path.write_text(expected, encoding="utf-8")
    world, routes = compile_world()
    print("World map: %d nodes, %d spaces, %d walking transitions, %d bus routes" % (
        len(world), sum(n['kind'] == 'location' for n in world.values()),
        sum(len(n['transitions']) for n in world.values()), sum(map(len, routes.values()))))
